"""Command line entry point for the EVerest API reference generator."""

import argparse
import sys

from everest_api.docs_generator import generate_reference
from everest_api.spec_loader import SpecError


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="python -m everest_api.docs_cli",
        description="Render the EVerest AsyncAPI specs as pages of the Sphinx manual: "
                    "one RST page per spec, the RST index page listing every API, and "
                    "the stylesheet and script the pages use.")
    parser.add_argument("--spec", nargs="+", action="extend", required=True, metavar="FILE",
                        help="AsyncAPI YAML specs of the reference (all in one directory)")
    parser.add_argument("--rst-out", required=True, metavar="DIR",
                        help="directory receiving <name>.rst per spec and the index page "
                             "autogenerated_api_index.rst")
    parser.add_argument("--assets-out", required=True, metavar="DIR",
                        help="directory receiving the stylesheet and script, below the "
                             "Sphinx static directory")

    args = parser.parse_args(argv)
    try:
        generate_reference(args.spec, args.rst_out, args.assets_out)
    except SpecError as err:
        print(f"error: {err}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
