"""Render the EVerest API specs as pages of the Sphinx manual.

Each spec becomes ``<name>.rst``: headings, labels and descriptions are RST,
the detail views (schema trees, messages, examples) raw HTML fragments. The
stylesheet and script those fragments need are written once for the Sphinx
static directory. An RST index page lists every API in a toctree.
"""

import re
from pathlib import Path

import jinja2 as j2
from markupsafe import Markup, escape

from everest_api.doc_model import build_doc_model, op_anchor, op_label, page_label, schema_anchor
from everest_api.spec_loader import SpecError, SpecSet, validate_spec

_TEMPLATES_DIR = Path(__file__).parent / "templates" / "rst"
_ASSETS_DIR = _TEMPLATES_DIR / "assets"
ASSET_FILES = ("everest-api.css", "everest-api.js")
INDEX_NAME = "autogenerated_api_index"

_LIST_ITEM = re.compile(r"^\s*[-*]\s+(.*)$")
_INLINE = re.compile(r"`([^`]+)`|\*\*([^*]+)\*\*")
_INLINE_MARKUP = re.compile(r"(`[^`]+`|\*\*[^*]+\*\*)")
_RST_SPECIAL = re.compile(r"([\\`*_|])")

# The HTML is assembled from these literals only; ``Markup.format`` and
# ``Markup.join`` escape every plain string they are given, so no text from
# the specs is ever wrapped in ``Markup`` unescaped.
_EMPTY = Markup("")
_PARAGRAPH = Markup("<p>{}</p>")
_LIST = Markup("<ul>{}</ul>")
_ITEM = Markup("<li>{}</li>")
_CODE = Markup("<code>{}</code>")
_BOLD = Markup("<strong>{}</strong>")


def _blocks(text):
    """Split the markdown subset the specs use into ("p", text) and
    ("ul", [item, ...]) blocks."""
    blocks = []
    for chunk in re.split(r"\n\s*\n", text.strip()):
        paragraph, items = [], []

        def flush_paragraph():
            if paragraph:
                blocks.append(("p", " ".join(paragraph)))
                paragraph.clear()

        def flush_items():
            if items:
                blocks.append(("ul", list(items)))
                items.clear()

        for line in chunk.splitlines():
            match = _LIST_ITEM.match(line)
            if match:
                flush_paragraph()
                items.append(match.group(1))
            elif items and line.startswith((" ", "\t")) and line.strip():
                items[-1] += " " + line.strip()
            else:
                flush_items()
                if line.strip():
                    paragraph.append(line.strip())
        flush_paragraph()
        flush_items()
    return blocks


def _inline(text):
    """Render inline code and bold; code keeps its content literal, bold may
    contain code."""
    parts = _INLINE.split(text)  # text, (code, bold, text)...
    out = [escape(parts[0])]
    for code, bold, tail in zip(parts[1::3], parts[2::3], parts[3::3]):
        out.append(_CODE.format(code) if code is not None else _BOLD.format(_inline(bold)))
        out.append(escape(tail))
    return _EMPTY.join(out)


def render_description(text):
    """Render the markdown subset the specs use as HTML: paragraphs, ``- ``
    lists, inline code and bold. Everything else is escaped text."""
    if not text:
        return _EMPTY
    out = []
    for kind, content in _blocks(text):
        if kind == "p":
            out.append(_PARAGRAPH.format(_inline(content)))
        else:
            out.append(_LIST.format(_EMPTY.join(_ITEM.format(_inline(i)) for i in content)))
    return _EMPTY.join(out)


def _escape(text):
    return _RST_SPECIAL.sub(r"\\\1", text)


def _guard_start(text):
    # a leading non-letter could start a list, enumeration, table, comment or section
    if text and not text[0].isalpha() and text[0] != "\\":
        return "\\" + text
    return text


def rst_escape(text):
    """Escape *text* so RST shows it literally as one line of inline text."""
    return _guard_start(_escape(" ".join(str(text).split())))


def _rst_inline(text):
    parts = _INLINE_MARKUP.split(" ".join(text.split()))
    out = ""
    for i, part in enumerate(parts):
        if i % 2 == 0:
            out += _escape(part)
            continue
        if part.startswith("**"):
            markup = "**" + _escape(part[2:-2].strip()) + "**"
        else:
            markup = "``" + part[1:-1].strip() + "``"
        # inline markup has to be delimited by whitespace or punctuation; an
        # escaped space is a delimiter that renders as nothing
        if out and not out[-1].isspace():
            out += "\\ "
        out += markup
        if parts[i + 1] and not parts[i + 1][0].isspace():
            out += "\\ "
    return _guard_start(out) if parts[0] else out


def render_rst_description(text):
    """Render the markdown subset the specs use as RST, like
    render_description does as HTML."""
    if not text:
        return ""
    out = []
    for kind, content in _blocks(text):
        if kind == "p":
            out.append(_rst_inline(content))
        else:
            out.append("\n".join(f"- {_rst_inline(item)}" for item in content))
    return "\n\n".join(out) + "\n"


def _make_env():
    env = j2.Environment(
        loader=j2.FileSystemLoader(str(_TEMPLATES_DIR)),
        autoescape=j2.select_autoescape(enabled_extensions=("html.j2",), default=False),
        lstrip_blocks=True,
        trim_blocks=True,
        undefined=j2.StrictUndefined,
        keep_trailing_newline=True,
    )
    env.filters["md"] = render_description
    env.filters["rst"] = render_rst_description
    env.filters["rst_escape"] = rst_escape
    env.globals["schema_anchor"] = schema_anchor
    env.globals["op_anchor"] = op_anchor
    env.globals["op_label"] = op_label
    env.globals["page_label"] = page_label
    return env


def _write_if_changed(path, content):
    """Leave a file with the same content untouched, so its modification time
    keeps Sphinx from reading the page again."""
    if path.is_file() and path.read_bytes() == content:
        return
    path.write_bytes(content)


def generate_page(spec_path, out_dir, specs=None, env=None):
    """Render the page of one spec as ``<out_dir>/<name>.rst``."""
    model = build_doc_model(spec_path, specs)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    content = (env or _make_env()).get_template("api_page.rst.j2").render(model=model)
    content = re.sub(r"\n{3,}", "\n\n", content)
    _write_if_changed(out_dir / f"{model.name}.rst", content.encode("utf-8"))
    return model


def write_assets(out_dir):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    for name in ASSET_FILES:
        _write_if_changed(out_dir / name, (_ASSETS_DIR / name).read_bytes())


def generate_reference(spec_files, rst_dir, assets_dir):
    """Render the whole reference: ``<rst_dir>/<name>.rst`` per spec, the
    index page ``<rst_dir>/autogenerated_api_index.rst`` and the shared
    assets in *assets_dir*. Every spec is validated against the AsyncAPI 3.0
    schema before anything is rendered. Nothing else in the directories is
    touched. The specs must share one directory, since they refer to each
    other by file name."""
    spec_files = [Path(p) for p in spec_files]
    directories = {p.resolve().parent for p in spec_files}
    if len(directories) != 1:
        raise SpecError("the specs of one reference must be in one directory")
    rst_dir = Path(rst_dir)
    specs = SpecSet(directories.pop())
    for spec in spec_files:
        validate_spec(specs.get(spec.name), spec.name)
    env = _make_env()
    models = []
    for spec in spec_files:
        try:
            models.append(generate_page(spec, rst_dir, specs=specs, env=env))
        except SpecError as err:
            raise SpecError(f"{spec.name}: {err}") from None
    write_assets(assets_dir)
    _write_if_changed(rst_dir / f"{INDEX_NAME}.rst",
                      env.get_template("api_index.rst.j2").render(models=models).encode("utf-8"))
    return models
