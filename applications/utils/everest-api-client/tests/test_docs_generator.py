class _PageParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids = set()
        self.hrefs = []
        self.inline_targets = []
        self.inline_scripts = 0
        self.styles = 0
        self.asset_urls = []
        self.s_names = set()
        self.codes = set()
        self._in = None
        self._script_has_src = False

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if "id" in attrs:
            self.ids.add(attrs["id"])
        if tag == "a" and "href" in attrs:
            self.hrefs.append(attrs["href"])
        if "data-inline" in attrs:
            self.inline_targets.append(attrs["data-inline"])
        if tag == "script":
            self._script_has_src = "src" in attrs
            if "src" in attrs:
                self.asset_urls.append(attrs["src"])
        if tag == "link" and attrs.get("rel") == "stylesheet":
            self.asset_urls.append(attrs["href"])
        if tag == "style":
            self.styles += 1
        if tag == "span" and attrs.get("class") == "s-name":
            self._in = "s-name"
        elif tag == "code":
            self._in = "code"

    def handle_endtag(self, tag):
        if tag in ("span", "code"):
            self._in = None

    def handle_data(self, data):
        if self.lasttag == "script" and not self._script_has_src and data.strip():
            self.inline_scripts += 1
        if self._in == "s-name":
            self.s_names.add(data.strip())
        elif self._in == "code":
            self.codes.add(data.strip())


@pytest.fixture(scope="module")
def site(tmp_path_factory):
    """All pages, the shared assets and the index, generated the way the docs
    build does."""
    root = tmp_path_factory.mktemp("api")
    generate_reference(SPEC_FILES, root, root / "autogenerated_api_index.rst")
    pages = {}
    for spec in SPEC_FILES:
        parser = _PageParser()
        parser.feed((root / spec.stem / "index.html").read_text(encoding="utf-8"))
        pages[spec.stem] = parser
    return root, pages


def test_specs_found():
    assert len(SPEC_FILES) > 20


def test_internal_links_resolve(site):
    root, pages = site
    for name, page in pages.items():
        for href in page.hrefs:
            if href.startswith("#"):
                assert href[1:] in page.ids, f"{name}: dangling {href}"
            elif href.startswith("../") and "/index.html#" in href:
                other, anchor = href[3:].split("/index.html#")
                if other in pages:
                    assert anchor in pages[other].ids, f"{name}: dangling {href}"


def test_on_demand_definitions_exist(site):
    _, pages = site
    for name, page in pages.items():
        for target in page.inline_targets:
            assert target in page.ids, f"{name}: no definition rendered for {target}"


def test_assets_shared_not_inlined(site):
    root, pages = site
    assert sorted(p.name for p in (root / "_assets").iterdir()) == sorted(ASSET_FILES)
    for name, page in pages.items():
        assert page.styles == 0, f"{name}: inline <style>"
        assert page.inline_scripts == 0, f"{name}: inline <script>"
        assert sorted(page.asset_urls) == ["../_assets/everest-api.css", "../_assets/everest-api.js"]
    copies = [p for p in root.rglob("*") if p.suffix in (".css", ".js") and p.parent.name != "_assets"]
    assert copies == []


@pytest.mark.parametrize("spec", SPEC_FILES, ids=lambda p: p.stem)
def test_nothing_from_the_spec_is_dropped(site, spec):
    """Every operation, message, schema, property name and enum value of the
    spec appears on its page."""
    _, pages = site
    page = pages[spec.stem]
    doc = load_spec(spec)
    for op_id in doc["operations"]:
        assert f"op-{op_id}" in page.ids
    for msg_id in doc["components"].get("messages", {}):
        assert f"msg-{msg_id}" in page.ids
    for schema_name, schema in doc["components"].get("schemas", {}).items():
        assert f"schema-{schema_name}" in page.ids
        for prop in _property_names(schema):
            assert prop in page.s_names, f"property {prop} of {schema_name} missing"
        for value in _enum_values(schema):
            assert html.unescape(str(value)) in page.codes, f"enum value {value} of {schema_name} missing"


def _walk(schema):
    if isinstance(schema, dict):
        yield schema
        for value in schema.values():
            yield from _walk(value)
    elif isinstance(schema, list):
        for value in schema:
            yield from _walk(value)


def _property_names(schema):
    for node in _walk(schema):
        if isinstance(node.get("properties"), dict):
            yield from node["properties"]


def _enum_values(schema):
    for node in _walk(schema):
        if isinstance(node.get("enum"), list):
            yield from node["enum"]


def test_reply_operations_link_to_their_request(tmp_path):
    out = tmp_path / "page"
    generate_html(SPECS_DIR / "auth_token_validator_API.yaml", out)
    text = (out / "index.html").read_text(encoding="utf-8")
    request = re.search(r'<article[^>]*id="op-receive_request_validate_token".*?</article>', text, re.S).group(0)
    assert '$message.header#/replyTo' in request
    assert 'href="#op-send_reply_validate_token"' in request
    reply = re.search(r'<article[^>]*id="op-send_reply_validate_token".*?</article>', text, re.S).group(0)
    assert 'href="#op-receive_request_validate_token"' in reply


def test_topics_join_prefix_and_address_with_one_slash(site):
    """Some specs write the server pathname with a trailing slash."""
    root, _ = site
    for page in root.glob("*/index.html"):
        topics = re.findall(r'data-copy="([^"]*)"', page.read_text(encoding="utf-8"))
        assert topics and all("//" not in t for t in topics), f"{page.parent.name}: {topics}"
    lifecycle = (root / "lifecycle_API" / "index.html").read_text(encoding="utf-8")
    assert 'data-copy="everest_api/1/lifecycle/m2e/stop_modules"' in lifecycle


def test_empty_payload_schema_means_no_payload(site):
    root, _ = site
    text = (root / "isolation_monitor_API" / "index.html").read_text(encoding="utf-8")
    start = re.search(r'<article[^>]*id="op-receive_start"', text).start()
    article = text[start:text.index("</article>", start)]
