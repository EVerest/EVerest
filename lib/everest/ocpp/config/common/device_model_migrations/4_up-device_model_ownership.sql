-- Monitors and stored runtime values are keyed by component and variable identity instead of a VARIABLE row, so they
-- can belong to variables that an owner registers at runtime. Absent instances, EVSE ids and connector ids are stored as
-- '' and 0, because SQLite treats NULLs as distinct in keys. Names and instances are case-insensitive, like the
-- identifiers of OCPP. A monitor belongs to its variable, whoever owns it. VARIABLE_ATTRIBUTE_VALUE.OWNER is the owner
-- of the registered variable a value belongs to; the component tables hold only the component config and need no owner.
ALTER TABLE VARIABLE_MONITORING RENAME TO VARIABLE_MONITORING_V3;

CREATE TABLE VARIABLE_MONITORING (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COMPONENT_NAME TEXT NOT NULL COLLATE NOCASE,
  COMPONENT_INSTANCE TEXT NOT NULL DEFAULT '' COLLATE NOCASE,
  EVSE_ID INTEGER NOT NULL DEFAULT 0,
  CONNECTOR_ID INTEGER NOT NULL DEFAULT 0,
  VARIABLE_NAME TEXT NOT NULL COLLATE NOCASE,
  VARIABLE_INSTANCE TEXT NOT NULL DEFAULT '' COLLATE NOCASE,
  SEVERITY INTEGER,
  "TRANSACTION" INTEGER,
  TYPE_ID INTEGER NOT NULL,
  CONFIG_TYPE_ID INTEGER,
  "VALUE" DECIMAL,
  REFERENCE_VALUE TEXT,
  FOREIGN KEY (TYPE_ID) REFERENCES MONITOR (ID) ON DELETE RESTRICT,
  FOREIGN KEY (CONFIG_TYPE_ID) REFERENCES MONITOR_CONFIG_TYPE (ID) ON DELETE RESTRICT
);

CREATE INDEX VARIABLE_MONITORING_NAME_KEY ON VARIABLE_MONITORING (
  COMPONENT_NAME, COMPONENT_INSTANCE, EVSE_ID, CONNECTOR_ID, VARIABLE_NAME, VARIABLE_INSTANCE
);

INSERT INTO VARIABLE_MONITORING (
  ID, COMPONENT_NAME, COMPONENT_INSTANCE, EVSE_ID, CONNECTOR_ID, VARIABLE_NAME, VARIABLE_INSTANCE,
  SEVERITY, "TRANSACTION", TYPE_ID, CONFIG_TYPE_ID, "VALUE", REFERENCE_VALUE
)
SELECT
  vm.ID, c.NAME, IFNULL(c.INSTANCE, ''), IFNULL(c.EVSE_ID, 0), IFNULL(c.CONNECTOR_ID, 0), v.NAME,
  IFNULL(v.INSTANCE, ''), vm.SEVERITY, vm."TRANSACTION", vm.TYPE_ID, vm.CONFIG_TYPE_ID, vm."VALUE",
  vm.REFERENCE_VALUE
FROM VARIABLE_MONITORING_V3 vm
JOIN VARIABLE v ON v.ID = vm.VARIABLE_ID
JOIN COMPONENT c ON c.ID = v.COMPONENT_ID;

-- Keep the id sequence, so ids of monitors that were deleted before are not handed out again.
DELETE FROM sqlite_sequence WHERE name = 'VARIABLE_MONITORING';
INSERT INTO sqlite_sequence (name, seq)
SELECT 'VARIABLE_MONITORING', seq FROM sqlite_sequence WHERE name = 'VARIABLE_MONITORING_V3';

DROP TABLE VARIABLE_MONITORING_V3;

-- EVSE and connector ids start at 1, so an id of 0 is stored as absent, which is what lookups without an EVSE or
-- connector match.
UPDATE COMPONENT SET EVSE_ID = NULL WHERE EVSE_ID = 0;
UPDATE COMPONENT SET CONNECTOR_ID = NULL WHERE CONNECTOR_ID = 0;

-- Components and variables that share a name key with a row of a lower id are removed. Names and instances are
-- case-insensitive. Lookups that ignore case returned the row with the lowest id, so that row holds the values in use.
-- The monitors of the removed rows are keyed by name and belong to the kept row. Variables that only a removed
-- component had are created again from the component config with their default value.
DELETE FROM VARIABLE WHERE COMPONENT_ID NOT IN (
  SELECT MIN(ID) FROM COMPONENT
  GROUP BY NAME COLLATE NOCASE, IFNULL(INSTANCE, '') COLLATE NOCASE, IFNULL(EVSE_ID, 0), IFNULL(CONNECTOR_ID, 0)
);
DELETE FROM COMPONENT WHERE ID NOT IN (
  SELECT MIN(ID) FROM COMPONENT
  GROUP BY NAME COLLATE NOCASE, IFNULL(INSTANCE, '') COLLATE NOCASE, IFNULL(EVSE_ID, 0), IFNULL(CONNECTOR_ID, 0)
);
DELETE FROM VARIABLE WHERE ID NOT IN (
  SELECT MIN(ID) FROM VARIABLE GROUP BY COMPONENT_ID, NAME COLLATE NOCASE, IFNULL(INSTANCE, '') COLLATE NOCASE
);
DELETE FROM VARIABLE_CHARACTERISTICS WHERE VARIABLE_ID NOT IN (SELECT ID FROM VARIABLE);
DELETE FROM VARIABLE_ATTRIBUTE WHERE VARIABLE_ID NOT IN (SELECT ID FROM VARIABLE);

CREATE TABLE VARIABLE_ATTRIBUTE_VALUE (
  COMPONENT_NAME TEXT NOT NULL COLLATE NOCASE,
  COMPONENT_INSTANCE TEXT NOT NULL DEFAULT '' COLLATE NOCASE,
  EVSE_ID INTEGER NOT NULL DEFAULT 0,
  CONNECTOR_ID INTEGER NOT NULL DEFAULT 0,
  VARIABLE_NAME TEXT NOT NULL COLLATE NOCASE,
  VARIABLE_INSTANCE TEXT NOT NULL DEFAULT '' COLLATE NOCASE,
  TYPE_ID INTEGER NOT NULL,
  "VALUE" TEXT,
  VALUE_SOURCE TEXT,
  OWNER TEXT,
  PRIMARY KEY (COMPONENT_NAME, COMPONENT_INSTANCE, EVSE_ID, CONNECTOR_ID, VARIABLE_NAME, VARIABLE_INSTANCE, TYPE_ID)
);

