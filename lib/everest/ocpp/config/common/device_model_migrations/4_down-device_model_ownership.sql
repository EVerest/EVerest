-- Monitors of variables without a VARIABLE row and the values in VARIABLE_ATTRIBUTE_VALUE cannot be represented in
-- schema 3 and are dropped. VARIABLE.SOURCE comes back empty.
ALTER TABLE VARIABLE_MONITORING RENAME TO VARIABLE_MONITORING_V4;

CREATE TABLE VARIABLE_MONITORING (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  VARIABLE_ID INTEGER NOT NULL,
  SEVERITY INTEGER,
  "TRANSACTION" INTEGER,
  TYPE_ID INTEGER NOT NULL,
  CONFIG_TYPE_ID INTEGER,
  "VALUE" DECIMAL,
  REFERENCE_VALUE TEXT,
  FOREIGN KEY (VARIABLE_ID) REFERENCES VARIABLE (ID) ON DELETE CASCADE,
  FOREIGN KEY (TYPE_ID) REFERENCES MONITOR (ID) ON DELETE RESTRICT,
  FOREIGN KEY (CONFIG_TYPE_ID) REFERENCES MONITOR_CONFIG_TYPE(ID) ON DELETE RESTRICT
);

INSERT INTO VARIABLE_MONITORING (
  ID, VARIABLE_ID, SEVERITY, "TRANSACTION", TYPE_ID, CONFIG_TYPE_ID, "VALUE", REFERENCE_VALUE
)
SELECT
  vm.ID, v.ID, vm.SEVERITY, vm."TRANSACTION", vm.TYPE_ID, vm.CONFIG_TYPE_ID, vm."VALUE", vm.REFERENCE_VALUE
FROM VARIABLE_MONITORING_V4 vm
JOIN COMPONENT c ON c.NAME = vm.COMPONENT_NAME COLLATE NOCASE
  AND IFNULL(c.INSTANCE, '') = vm.COMPONENT_INSTANCE COLLATE NOCASE
  AND IFNULL(c.EVSE_ID, 0) = vm.EVSE_ID AND IFNULL(c.CONNECTOR_ID, 0) = vm.CONNECTOR_ID
JOIN VARIABLE v ON v.COMPONENT_ID = c.ID AND v.NAME = vm.VARIABLE_NAME COLLATE NOCASE
  AND IFNULL(v.INSTANCE, '') = vm.VARIABLE_INSTANCE COLLATE NOCASE;

DELETE FROM sqlite_sequence WHERE name = 'VARIABLE_MONITORING';
INSERT INTO sqlite_sequence (name, seq)
SELECT 'VARIABLE_MONITORING', seq FROM sqlite_sequence WHERE name = 'VARIABLE_MONITORING_V4';

DROP TABLE VARIABLE_MONITORING_V4;

DROP TABLE VARIABLE_ATTRIBUTE_VALUE;

ALTER TABLE VARIABLE
ADD COLUMN SOURCE TEXT;
