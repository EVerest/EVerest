-- Migration 4: Multi-config support
-- Replaces SETTING with CONFIG (lightweight identity anchor).
-- ManagerSettings (paths, MQTT, controller settings) are no longer stored in the
-- database
-- Removes the single-row restriction so multiple configs can coexist.
-- Adds CONFIG_ID scoping to MODULE and all its child tables, with cascading deletes
-- rooted at CONFIG so that deleting a CONFIG row removes everything belonging to it.
-- fix Mutability and Datatype tables
--
-- NOTE: foreign-key enforcement is disabled by the SchemaUpdater for the duration of the
-- migration transaction ("PRAGMA foreign_keys" would be a no-op inside it).

-- 0. Remove configs marked invalid. FK enforcement is off during migration,
--    so ON DELETE CASCADE does not fire — delete children explicitly.
DELETE FROM MODULE_FULFILLMENT   WHERE EXISTS (SELECT 1 FROM CONFIG_META WHERE VALID = 0);
DELETE FROM MODULE_TIER_MAPPING  WHERE EXISTS (SELECT 1 FROM CONFIG_META WHERE VALID = 0);
DELETE FROM CONFIGURATION        WHERE EXISTS (SELECT 1 FROM CONFIG_META WHERE VALID = 0);
DELETE FROM CONFIG_ACCESS        WHERE EXISTS (SELECT 1 FROM CONFIG_META WHERE VALID = 0);
DELETE FROM MODULE_CONFIG_ACCESS WHERE EXISTS (SELECT 1 FROM CONFIG_META WHERE VALID = 0);
DELETE FROM MODULE               WHERE EXISTS (SELECT 1 FROM CONFIG_META WHERE VALID = 0);
DELETE FROM CONFIG_META          WHERE VALID = 0;
DELETE FROM SETTING              WHERE NOT EXISTS (SELECT 1 FROM CONFIG_META);

-- 1. CONFIG: lightweight identity table - replaces SETTING as the cascade root.
CREATE TABLE CONFIG (
    ID INTEGER PRIMARY KEY
);
INSERT INTO CONFIG (ID) SELECT ID FROM SETTING;

DROP TABLE SETTING;

-- 2. CONFIG_META: update FK from SETTING to CONFIG; add DESCRIPTION column.
CREATE TABLE CONFIG_META_NEW (
    ID               INTEGER PRIMARY KEY REFERENCES CONFIG (ID) ON DELETE CASCADE,
    LAST_UPDATED     TEXT    NOT NULL,
    CONFIG_DUMP      TEXT    NOT NULL,
    CONFIG_FILE_PATH TEXT,
    DESCRIPTION      TEXT
);
INSERT INTO CONFIG_META_NEW SELECT ID, LAST_UPDATED, CONFIG_DUMP, CONFIG_FILE_PATH, NULL FROM CONFIG_META;
DROP TABLE CONFIG_META;
ALTER TABLE CONFIG_META_NEW RENAME TO CONFIG_META;

-- 3. MODULE: add CONFIG_ID, composite PK (CONFIG_ID, ID). FK references CONFIG.
CREATE TABLE MODULE_NEW (
    CONFIG_ID    INTEGER NOT NULL REFERENCES CONFIG (ID) ON DELETE CASCADE,
    ID           TEXT    NOT NULL,
    NAME         TEXT    NOT NULL,
    STANDALONE   INTEGER,
    CAPABILITIES TEXT,
    PRIMARY KEY (CONFIG_ID, ID)
);
INSERT INTO MODULE_NEW SELECT 0, ID, NAME, STANDALONE, CAPABILITIES FROM MODULE;
DROP TABLE MODULE;
ALTER TABLE MODULE_NEW RENAME TO MODULE;

-- 4. MODULE_FULFILLMENT: composite FK on (CONFIG_ID, MODULE_ID) and (CONFIG_ID, IMPLEMENTATION_MODULE_ID).
-- REQUIREMENT_INDEX stores the position of a fulfillment within its requirement, as listed in the
-- config. Requirements are resolved positionally (see Requirement::index), so this order has to
-- survive the round trip through the database.
CREATE TABLE MODULE_FULFILLMENT_NEW (
    CONFIG_ID                INTEGER NOT NULL,
    MODULE_ID                TEXT    NOT NULL,
    REQUIREMENT_NAME         TEXT    NOT NULL,
    REQUIREMENT_INDEX        INTEGER NOT NULL,
    IMPLEMENTATION_ID        TEXT    NOT NULL,
    IMPLEMENTATION_MODULE_ID TEXT    NOT NULL,
    PRIMARY KEY (CONFIG_ID, MODULE_ID, REQUIREMENT_NAME, REQUIREMENT_INDEX),
    FOREIGN KEY (CONFIG_ID, MODULE_ID)                REFERENCES MODULE (CONFIG_ID, ID) ON DELETE CASCADE,
    FOREIGN KEY (CONFIG_ID, IMPLEMENTATION_MODULE_ID) REFERENCES MODULE (CONFIG_ID, ID) ON DELETE CASCADE
);
-- Databases predating this column carry no ordering information, so keep the order they were
-- previously read back in instead of inventing a new one.
INSERT INTO MODULE_FULFILLMENT_NEW
    SELECT 0, MODULE_ID, REQUIREMENT_NAME,
           ROW_NUMBER() OVER (PARTITION BY MODULE_ID, REQUIREMENT_NAME
                              ORDER BY IMPLEMENTATION_ID, IMPLEMENTATION_MODULE_ID) - 1,
           IMPLEMENTATION_ID, IMPLEMENTATION_MODULE_ID
    FROM MODULE_FULFILLMENT;
DROP TABLE MODULE_FULFILLMENT;
ALTER TABLE MODULE_FULFILLMENT_NEW RENAME TO MODULE_FULFILLMENT;

