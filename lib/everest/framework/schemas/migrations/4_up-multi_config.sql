-- 9. BOOT_CONFIG: single-row table storing next-boot slot selection.
-- Only an *explicit* selection is stored; the absence of a row means "use slot 0". That is also
-- the bootstrap state of a fresh database, where no CONFIG row exists yet and slot 0 is merely
-- where the first config will be seeded. Because only resolvable selections are ever stored, the
-- foreign key can guarantee the pointer never dangles: deleting a slot that is marked for the
-- next boot is rejected (RESTRICT) instead of silently leaving the selection pointing at nothing.
--
-- The ID column exists to make UPSERT operations possible (ID in the ON CONFLICT target)
CREATE TABLE BOOT_CONFIG (
    ID                INTEGER PRIMARY KEY CHECK (ID = 0),
    NEXT_BOOT_SLOT_ID INTEGER NOT NULL REFERENCES CONFIG (ID) ON DELETE RESTRICT
);
-- Upgraded databases carry their original config at slot 0, so there is something valid to point
-- at. Fresh databases have an empty CONFIG at this point and stay deliberately row-less.
INSERT INTO BOOT_CONFIG (ID, NEXT_BOOT_SLOT_ID) SELECT 0, ID FROM CONFIG WHERE ID = 0;

