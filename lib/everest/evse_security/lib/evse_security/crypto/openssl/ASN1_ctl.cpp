std::vector<std::uint8_t> encode_der(const TrustList& ctl) {
    CtlPtr a = to_asn1(ctl);

    unsigned char* raw = nullptr;
    const int len = i2d_Asn1CtlEvpkiCtl(a.get(), &raw);
    if (len <= 0 || raw == nullptr) {
        throw std::runtime_error("i2d_Asn1CtlEvpkiCtl failed");
    }

    std::vector<std::uint8_t> out(raw, raw + len);
    OPENSSL_free(raw);
    return out;
}

TrustList decode_der(const std::uint8_t* der, std::size_t len) {
    if (!der || len == 0) {
        throw std::runtime_error("empty input");
    }

    const unsigned char* p = der;
    CtlPtr a(d2i_Asn1CtlEvpkiCtl(nullptr, &p, static_cast<long>(len)),
             &Asn1CtlEvpkiCtl_free);
    if (!a) {
        throw std::runtime_error("d2i_Asn1CtlEvpkiCtl failed");
    }
    if (p != der + len) {
        throw std::runtime_error("trailing bytes after CTL");
    }

    return from_asn1(*a);
}

TrustList decode_der(const std::vector<std::uint8_t>& der) {
    return decode_der(der.data(), der.size());
}

